hl.on("hyprland.start", function()
	hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
	hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
	hl.exec_cmd("killall -q xdg-desktop-portal-hyprland xdg-desktop-portal-wlr xdg-desktop-portal || true")
	hl.exec_cmd("test -x /usr/lib/xdg-desktop-portal-hyprland && /usr/lib/xdg-desktop-portal-hyprland &")
	hl.exec_cmd("test -x /usr/lib/xdg-desktop-portal && /usr/lib/xdg-desktop-portal &")
	hl.exec_cmd("hyprshade on vibrance")
	-- Bar: Quickshell (Serpantinum)
	hl.exec_cmd("$HOME/.local/bin/serpantinumd start &")
	hl.exec_cmd("rm -f $HOME/.cache/spotify/Singleton* && sleep 4 && spotify &")
	hl.exec_cmd("rm -f $HOME/.config/BeeperTexts/Singleton* && sleep 4 && beeper &")
	hl.exec_cmd("awww-daemon --format xrgb")
	hl.exec_cmd("sleep 1 && awww img $HOME/Downloads/wallpapers/spiderman.png")
	hl.exec_cmd("clipse -listen")
	hl.exec_cmd("command -v kdeconnectd >/dev/null && kdeconnectd")
	hl.exec_cmd("command -v kdeconnect-indicator >/dev/null && kdeconnect-indicator")
	hl.exec_cmd("~/.config/Scripts/battery_notif.sh")
	hl.exec_cmd("~/.config/Scripts/bongocat.sh &")
	hl.exec_cmd("systemctl --user enable --now hyprpolkitagent.service")
	hl.exec_cmd("systemctl --user enable --now hypridle.service")
end)
